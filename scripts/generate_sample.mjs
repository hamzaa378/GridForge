/** Regenerate the bundled importable XLSX example with the application's own OOXML writer. */
import { writeFile, mkdir } from 'node:fs/promises';
import {Workbook} from '../dist/engine/workbook.js';
import {SpreadsheetDocument} from '../dist/engine/document.js';
import {exportXlsx} from '../dist/engine/xlsx.js';
const w=new Workbook();w.applyEdits([
  {ref:'A1',raw:'Product'},{ref:'B1',raw:'Units'},{ref:'C1',raw:'Price'},{ref:'D1',raw:'Revenue'},
  {ref:'A2',raw:'Keyboard'},{ref:'B2',raw:'50'},{ref:'C2',raw:'1500'},{ref:'D2',raw:'=B2*C2'},
  {ref:'A3',raw:'Mouse'},{ref:'B3',raw:'10'},{ref:'C3',raw:'500'},{ref:'D3',raw:'=B3*C3'},
  {ref:'A4',raw:'Monitor'},{ref:'B4',raw:'80'},{ref:'C4',raw:'12000'},{ref:'D4',raw:'=B4*C4'},
  {ref:'A5',raw:'Webcam'},{ref:'B5',raw:'25'},{ref:'C5',raw:'2500'},{ref:'D5',raw:'=B5*C5'},
  {ref:'A7',raw:'Total revenue'},{ref:'D7',raw:'=SUM(D2:D5)'}
],false);w.patchStyles(['A1','B1','C1','D1'],{bold:true,background:'#244876',color:'#ffffff'});
w.patchStyles(['C2','C3','C4','C5','D2','D3','D4','D5','D7'],{numberFormat:'currency'});
const doc=new SpreadsheetDocument(w);doc.renameSheet(doc.activeId,'Sales');
doc.active.tools.freezeRows=1;doc.active.tools.filter={startRow:0,endRow:4,startCol:0,endCol:3,column:0,query:''};
doc.active.tools.conditional.push({start:'D2',end:'D5',operator:'gt',threshold:100000,color:'#246a53'});
doc.addSheet('Summary');doc.active.book.applyEdits([{ref:'A1',raw:'Workbook Notes'},{ref:'A2',raw:'Data, formulas and formatting are generated by GridForge.'},{ref:'A3',raw:'Use the Sales tab to test sorting, filtering and conditional rules.'}],false);
await mkdir('examples',{recursive:true});await writeFile('examples/sample_sales.xlsx',exportXlsx(doc));
console.log('examples/sample_sales.xlsx generated using GridForge OOXML writer');
